import { randomBytes, randomUUID } from 'node:crypto';
import * as path from 'node:path';
import { canonicalize, digestCanonical, JsonValue, ProcedureMetadataV1, validateProcedureMetadata } from './contracts';
import { ApprovalHistoryError, ApprovalHistoryEventReferenceV1, ApprovalHistoryPersistence, HistoricalApprovalRecordV1 } from './approvalHistory';
import { HistoricalStartCommitmentV1, ValidationLifecycleStore } from './validationLifecycle';

export const CONTROLLED_VALIDATION_CONSENT_DISCLOSURE_VERSION = 'm22.3.2-option-a-v1';
export const CONTROLLED_VALIDATION_APPROVAL_TTL_MS = 5 * 60 * 1000;

export const CONTROLLED_VALIDATION_CONSENT_DISCLOSURE = 'Controlled Validation executes a bounded security procedure. Core enforces the approved project scope and procedure restrictions. The same-user local-caller limitation is accepted: Core cannot cryptographically prove that this request came from the official VS Code or Desktop UI, and another process running as this OS user may imitate this flow. V1 permits offline, read-only, user-selected project-local procedures only. This approval is limited to the exact project, targets, procedure, arguments, evidence, capabilities, and limits shown, for one run before expiry. Procedures cannot modify the project, access the network, or inherit provider credentials or unrelated secrets. Procedure completion alone does not confirm a vulnerability.';

export interface ControlledValidationProjectScopeV1 {
	root: string;
	identity: string;
	permittedTargets: string[];
}

export interface ControlledValidationProcedureIdentityV1 {
	id: string;
	version: string;
	artifactDigest: string;
}

export interface ControlledValidationEvidenceIdentityV1 {
	snapshotId: string;
	digest: string;
}

export interface ControlledValidationCapabilitiesV1 {
	filesystem: 'none' | 'read-only' | 'read-write';
	network: 'none' | 'restricted' | 'unrestricted';
	projectWrites: boolean;
	inheritedCredentials: boolean;
}

export interface ControlledValidationApprovedCapabilitiesV1 {
	filesystem: 'none' | 'read-only';
	network: 'none';
	projectWrites: false;
	inheritedCredentials: false;
}

export interface ControlledValidationResourceLimitsV1 {
	timeoutMs: number;
	memoryBytes: number;
	outputBytes: number;
	processCount: number;
}

/** Client-supplied authorization intent. Approval IDs, nonce and timestamps are generated by Core. */
export interface ControlledValidationAuthorizationRequestV1 {
	schemaVersion: 1;
	requestId: string;
	consent: { disclosureVersion: typeof CONTROLLED_VALIDATION_CONSENT_DISCLOSURE_VERSION; confirmed: true };
	project: ControlledValidationProjectScopeV1;
	procedure: ControlledValidationProcedureIdentityV1;
	arguments: JsonValue;
	argumentDigest: string;
	evidence: ControlledValidationEvidenceIdentityV1;
	capabilities: ControlledValidationCapabilitiesV1;
	resourceLimits: ControlledValidationResourceLimitsV1;
}

export type ControlledValidationAuthorizationStatusV1 = 'approved' | 'consumed' | 'revoked' | 'expired' | 'invalidated-by-restart';

export interface ActiveControlledValidationApprovalV1 {
	schemaVersion: 1;
	approvalId: string;
	nonce: string;
	createdAt: string;
	expiresAt: string;
	status: ControlledValidationAuthorizationStatusV1;
	nonExecutable: true;
	coreEpoch: string;
	requestId: string;
	requestDigest: string;
	project: ControlledValidationProjectScopeV1;
	procedure: ControlledValidationProcedureIdentityV1;
	arguments: JsonValue;
	argumentDigest: string;
	evidence: ControlledValidationEvidenceIdentityV1;
	inputSchemaDigest: string;
	policyDigest: string;
	capabilities: ControlledValidationApprovedCapabilitiesV1;
	resourceLimits: ControlledValidationResourceLimitsV1;
}

export type ControlledValidationAuthorizationRejectionCode =
	| 'INVALID_REQUEST' | 'INVALID_PROJECT_SCOPE' | 'TARGET_OUT_OF_SCOPE' | 'PROCEDURE_NOT_FOUND'
	| 'PROCEDURE_IDENTITY_MISMATCH' | 'PROCEDURE_VERIFICATION_UNAVAILABLE' | 'PROCEDURE_NOT_VERIFIED'
	| 'ARGUMENT_SCHEMA_UNAVAILABLE' | 'ARGUMENT_SCHEMA_INVALID' | 'ARGUMENT_DIGEST_MISMATCH'
	| 'EVIDENCE_UNAVAILABLE' | 'EVIDENCE_STALE' | 'CAPABILITY_UNSUPPORTED' | 'RESOURCE_LIMIT_EXCEEDED'
	| 'CONSENT_REQUIRED' | 'APPROVAL_EXPIRED' | 'APPROVAL_REVOKED' | 'APPROVAL_NOT_FOUND'
	| 'APPROVAL_BINDING_MISMATCH' | 'APPROVAL_ALREADY_CONSUMED' | 'DUPLICATE_APPROVAL_ID' | 'NONCE_REUSE' | 'APPROVAL_REPLAY' | 'HISTORY_STORAGE_UNAVAILABLE' | 'DEPENDENCY_UNAVAILABLE'
	| 'APPROVAL_NON_EXECUTABLE';

export type ControlledValidationAuthorizationResult =
	| { ok: true; approval: ActiveControlledValidationApprovalV1 }
	| { ok: false; code: ControlledValidationAuthorizationRejectionCode; message: string };

export interface ConsumedControlledValidationAuthorizationV1 { schemaVersion: 1; approvalId: string; executionId: string; commitmentEventId: string; authorizationBindingDigest: string; consumedAt: string; status: 'consumed'; nonExecutable: true; }
export type ControlledValidationStartCommitResultV1 = { ok: true; duplicate: boolean; receipt: ConsumedControlledValidationAuthorizationV1 }
	| { ok: false; code: 'APPROVAL_NOT_FOUND' | 'APPROVAL_REVOKED' | 'APPROVAL_EXPIRED' | 'APPROVAL_ALREADY_CONSUMED' | 'APPROVAL_BINDING_MISMATCH' | 'START_COMMIT_UNAVAILABLE'; message: string; historical?: HistoricalStartCommitmentV1 };

export interface VerifiedControlledValidationProcedure {
	metadata: ProcedureMetadataV1;
	artifactDigest: string;
	inputSchemaDigest: string;
	policyDigest: string;
	/** Only a release-pinned catalog verifier may set this true. */
	verified: true;
	validateArguments(value: JsonValue): boolean;
}

export interface ControlledValidationAuthorizationDependencies {
	resolveProject(root: string): Promise<{ canonicalRoot: string; identity: string }>;
	validateProjectTargets(project: { canonicalRoot: string; identity: string }, targets: string[]): Promise<boolean>;
	resolveVerifiedProcedure(id: string, version: string): Promise<VerifiedControlledValidationProcedure | undefined>;
	resolveCurrentEvidence(snapshotId: string): Promise<{ digest: string; current: boolean } | undefined>;
	validatePolicy(input: {
		capabilities: ControlledValidationCapabilitiesV1;
		resourceLimits: ControlledValidationResourceLimitsV1;
		procedure: ProcedureMetadataV1;
	}): boolean;
}

export interface ControlledValidationAuthorizationClock {
	wallNow(): number;
	monotonicNow(): number;
}

export interface ControlledValidationAuthorizationIdSource {
	approvalId(): string;
	nonce(): string;
	epoch(): string;
}

export interface ControlledValidationAuthorizationLockTimer {
	setTimeout(callback: () => void, milliseconds: number): unknown;
	clearTimeout(handle: unknown): void;
}

const defaultClock: ControlledValidationAuthorizationClock = {
	wallNow: () => Date.now(),
	monotonicNow: () => Number(process.hrtime.bigint()) / 1_000_000,
};

const defaultIds: ControlledValidationAuthorizationIdSource = {
	approvalId: () => randomUUID(),
	nonce: () => randomBytes(32).toString('hex'),
	epoch: () => randomUUID(),
};

const defaultLockTimer: ControlledValidationAuthorizationLockTimer = {
	setTimeout: (callback, milliseconds) => setTimeout(callback, milliseconds),
	clearTimeout: handle => clearTimeout(handle as ReturnType<typeof setTimeout>),
};

class AuthorizationLockTimeoutError extends Error {
	constructor() { super('Authorization lock acquisition timed out; no state change was made.'); this.name = 'AuthorizationLockTimeoutError'; }
}

/**
 * In-memory authorization foundation only. It has no persistence, consume/start,
 * protocol, executor, or worker path. Missing production dependencies fail closed.
 */
export class ControlledValidationAuthorizationService {
	private readonly epoch: string;
	private readonly approvals = new Map<string, { record: ActiveControlledValidationApprovalV1; monotonicDeadline: number; approvalHistory: ApprovalHistoryEventReferenceV1 }>();
	private readonly ids = new Set<string>();
	private readonly nonces = new Set<string>();
	private readonly requestDigests = new Map<string, string>();
	private readonly approvalLocks = new Map<string, Promise<void>>();

	constructor(
		private readonly dependencies: ControlledValidationAuthorizationDependencies,
		private readonly history: ApprovalHistoryPersistence,
		private readonly lifecycle?: ValidationLifecycleStore,
		private readonly clock: ControlledValidationAuthorizationClock = defaultClock,
		private readonly idSource: ControlledValidationAuthorizationIdSource = defaultIds,
		private readonly lockTimer: ControlledValidationAuthorizationLockTimer = defaultLockTimer,
	) {
		this.epoch = idSource.epoch();
		if (!isUuid(this.epoch)) { throw new TypeError('Core authorization epoch source returned an invalid ID.'); }
	}

	async approve(value: unknown): Promise<ControlledValidationAuthorizationResult> {
		let request: ControlledValidationAuthorizationRequestV1;
		try { request = validateControlledValidationAuthorizationRequest(value); }
		catch (error) { return reject('INVALID_REQUEST', errorMessage(error)); }
		if (request.consent.confirmed !== true || request.consent.disclosureVersion !== CONTROLLED_VALIDATION_CONSENT_DISCLOSURE_VERSION) {
			return reject('CONSENT_REQUIRED', 'The current Controlled Validation consent disclosure must be acknowledged.');
		}
		const intentDigest = digestCanonical(request);
		const priorRequest = this.requestDigests.get(request.requestId);
		if (priorRequest) {
			if (priorRequest !== intentDigest) { return reject('APPROVAL_BINDING_MISMATCH', 'The request ID was reused with different authorization content.'); }
			const previous = [...this.approvals.values()].find(item => item.record.requestId === request.requestId);
			if (previous) { return await this.validate(previous.record.approvalId, request); }
		}
		let historical: HistoricalApprovalRecordV1[];
		try { historical = await this.history.query(); }
		catch { return reject('HISTORY_STORAGE_UNAVAILABLE', 'Durable approval history is unavailable; Core did not issue an approval.'); }
		if (historical.some(record => record.requestId === request.requestId)) { return reject('APPROVAL_REPLAY', 'This approval request was already recorded; submit a new reviewed request.'); }

		let project: { canonicalRoot: string; identity: string };
		let procedure: VerifiedControlledValidationProcedure | undefined;
		let evidence: { digest: string; current: boolean } | undefined;
		let targetsValid = false;
		try {
			project = await this.dependencies.resolveProject(request.project.root);
			if (!sameCanonicalRoot(request.project.root, project.canonicalRoot) || request.project.identity !== project.identity) {
				return reject('INVALID_PROJECT_SCOPE', 'Project root or identity is not canonical and Core-verified.');
			}
			targetsValid = await this.dependencies.validateProjectTargets(project, request.project.permittedTargets);
			procedure = await this.dependencies.resolveVerifiedProcedure(request.procedure.id, request.procedure.version);
			evidence = await this.dependencies.resolveCurrentEvidence(request.evidence.snapshotId);
		} catch {
			return reject('DEPENDENCY_UNAVAILABLE', 'Core could not validate required project, procedure, or evidence state.');
		}
		if (!targetsValid) { return reject('TARGET_OUT_OF_SCOPE', 'A permitted target is outside the selected project or cannot be safely resolved.'); }
		if (!procedure) { return reject('PROCEDURE_VERIFICATION_UNAVAILABLE', 'No verified procedure catalog entry is available.'); }
		if (procedure.metadata.id !== request.procedure.id || procedure.metadata.version !== request.procedure.version || procedure.metadata.packageDigest !== request.procedure.artifactDigest || procedure.artifactDigest !== request.procedure.artifactDigest) {
			return reject('PROCEDURE_IDENTITY_MISMATCH', 'Procedure ID, immutable version, or artifact digest does not match the verified catalog entry.');
		}
		try { validateProcedureMetadata(procedure.metadata); }
		catch { return reject('PROCEDURE_NOT_VERIFIED', 'Procedure catalog metadata is malformed or claims unsupported verification state.'); }
		if (!isDigest(procedure.inputSchemaDigest) || !isDigest(procedure.policyDigest) || procedure.verified !== true || procedure.metadata.signature.state !== 'unverified' || procedure.metadata.retirement !== 'active') {
			return reject('PROCEDURE_NOT_VERIFIED', 'Procedure catalog entry is not verified and active.');
		}
		if (!procedure.validateArguments) { return reject('ARGUMENT_SCHEMA_UNAVAILABLE', 'The verified procedure input schema is unavailable.'); }
		if (!procedure.validateArguments(request.arguments)) { return reject('ARGUMENT_SCHEMA_INVALID', 'Arguments do not match the procedure input schema.'); }
		if (canonicalDigest(request.arguments) !== request.argumentDigest) { return reject('ARGUMENT_DIGEST_MISMATCH', 'Argument digest does not match Core canonicalization.'); }
		if (!evidence) { return reject('EVIDENCE_UNAVAILABLE', 'Core cannot resolve the requested evidence snapshot.'); }
		if (!evidence.current || evidence.digest !== request.evidence.digest) { return reject('EVIDENCE_STALE', 'Evidence snapshot is stale or its digest changed.'); }
		if (request.capabilities.network !== 'none' || request.capabilities.projectWrites !== false || request.capabilities.inheritedCredentials !== false || !['none','read-only'].includes(request.capabilities.filesystem)) {
			return reject('CAPABILITY_UNSUPPORTED', 'Requested capability exceeds the offline, read-only v1 boundary.');
		}
		if (!this.withinProcedureCeilings(request.resourceLimits, procedure.metadata)) { return reject('RESOURCE_LIMIT_EXCEEDED', 'Requested resource limits exceed the verified procedure ceilings.'); }
		try {
			if (!this.dependencies.validatePolicy({ capabilities: request.capabilities, resourceLimits: request.resourceLimits, procedure: procedure.metadata })) {
				return reject('CAPABILITY_UNSUPPORTED', 'Requested capabilities or limits exceed Core policy.');
			}
		} catch { return reject('DEPENDENCY_UNAVAILABLE', 'Core policy validation is unavailable.'); }

		const createdAtMs = this.clock.wallNow();
		const monotonicNow = this.clock.monotonicNow();
		if (!Number.isFinite(createdAtMs) || Math.abs(createdAtMs) > 8.64e15 || !Number.isFinite(monotonicNow) || monotonicNow < 0) { return reject('DEPENDENCY_UNAVAILABLE', 'Core clock is unavailable.'); }
		let approvalId: string;
		let nonce: string;
		try { approvalId = this.idSource.approvalId(); nonce = this.idSource.nonce(); }
		catch { return reject('DEPENDENCY_UNAVAILABLE', 'Core approval identifier generation is unavailable.'); }
		if (!isUuid(approvalId) || this.ids.has(approvalId)) { return reject('DUPLICATE_APPROVAL_ID', 'Core generated an invalid or duplicate approval identifier.'); }
		if (!/^[a-f0-9]{64}$/.test(nonce) || this.nonces.has(nonce)) { return reject('NONCE_REUSE', 'Core generated an invalid or previously used nonce.'); }
		const createdAt = new Date(createdAtMs).toISOString();
		const expiresAt = new Date(createdAtMs + CONTROLLED_VALIDATION_APPROVAL_TTL_MS).toISOString();
		const record: ActiveControlledValidationApprovalV1 = deepFreeze({
			schemaVersion: 1, approvalId, nonce, createdAt, expiresAt, status: 'approved', nonExecutable: true,
			coreEpoch: this.epoch, requestId: request.requestId, requestDigest: intentDigest,
			project: clone(request.project), procedure: clone(request.procedure), arguments: clone(request.arguments),
			argumentDigest: request.argumentDigest, evidence: clone(request.evidence), inputSchemaDigest: procedure.inputSchemaDigest, policyDigest: procedure.policyDigest,
			capabilities: { filesystem: request.capabilities.filesystem as 'none' | 'read-only', network: 'none', projectWrites: false, inheritedCredentials: false }, resourceLimits: clone(request.resourceLimits),
		});
		let issuedHistoryReference: ApprovalHistoryEventReferenceV1;
		try {
			issuedHistoryReference = await this.history.recordIssued({
				approvalId, requestId: request.requestId, requestDigest: intentDigest, createdAt, expiresAt,
				projectIdentity: request.project.identity, permittedScopeDigest: `sha256:${digestCanonical(request.project.permittedTargets)}`,
				procedureId: request.procedure.id, procedureVersion: request.procedure.version, artifactDigest: request.procedure.artifactDigest,
				argumentDigest: request.argumentDigest, evidenceSnapshotId: request.evidence.snapshotId, evidenceDigest: request.evidence.digest,
				capabilities: record.capabilities, resourceLimits: record.resourceLimits,
			});
		} catch (error) {
			if (error instanceof ApprovalHistoryError && /identifier already exists|request ID was already recorded/i.test(error.message)) { return reject('APPROVAL_REPLAY', error.message); }
			return reject('HISTORY_STORAGE_UNAVAILABLE', 'Approval history could not be durably recorded; no approval was issued.');
		}
		this.ids.add(approvalId);
		this.nonces.add(nonce);
		this.requestDigests.set(request.requestId, intentDigest);
		this.approvals.set(approvalId, { record, monotonicDeadline: monotonicNow + CONTROLLED_VALIDATION_APPROVAL_TTL_MS, approvalHistory: issuedHistoryReference });
		return { ok: true, approval: clone(record) };
	}

	async validate(approvalId: string, candidate: unknown): Promise<ControlledValidationAuthorizationResult> {
		return await this.withApprovalLock(approvalId, () => this.validateUnlocked(approvalId, candidate));
	}

	private async validateUnlocked(approvalId: string, candidate: unknown): Promise<ControlledValidationAuthorizationResult> {
		const current = this.approvals.get(approvalId);
		if (!current) { return reject('APPROVAL_NOT_FOUND', 'Approval is unavailable in this Core process.'); }
		if (current.record.status === 'consumed') { return reject('APPROVAL_ALREADY_CONSUMED', 'Approval has already been consumed by a durable start commitment.'); }
		if (current.record.status === 'revoked') { return reject('APPROVAL_REVOKED', 'Approval has been revoked.'); }
		if (current.record.status !== 'approved' || current.record.coreEpoch !== this.epoch) { return reject('APPROVAL_EXPIRED', 'Approval is not current in this Core process.'); }
		if (this.clock.monotonicNow() >= current.monotonicDeadline) {
			this.replaceStatus(approvalId, 'expired');
			try { await this.history.recordStatus(approvalId, 'expired', new Date(this.clock.wallNow()).toISOString()); }
			catch { return reject('HISTORY_STORAGE_UNAVAILABLE', 'Approval expired and was invalidated, but its history event could not be recorded.'); }
			return reject('APPROVAL_EXPIRED', 'Approval has expired.');
		}
		let request: ControlledValidationAuthorizationRequestV1;
		try { request = validateControlledValidationAuthorizationRequest(candidate); }
		catch (error) { return reject('INVALID_REQUEST', errorMessage(error)); }
		if (digestCanonical(request) !== current.record.requestDigest || request.requestId !== current.record.requestId) {
			return reject('APPROVAL_BINDING_MISMATCH', 'Approval request binding changed.');
		}
		try {
			const project = await this.dependencies.resolveProject(request.project.root);
			if (!sameCanonicalRoot(request.project.root, project.canonicalRoot) || request.project.identity !== project.identity
				|| !await this.dependencies.validateProjectTargets(project, request.project.permittedTargets)) {
				return reject('INVALID_PROJECT_SCOPE', 'Approved project or target scope is no longer current.');
			}
			const procedure = await this.dependencies.resolveVerifiedProcedure(request.procedure.id, request.procedure.version);
			if (!procedure) { return reject('PROCEDURE_VERIFICATION_UNAVAILABLE', 'No verified procedure catalog entry is available.'); }
			try { validateProcedureMetadata(procedure.metadata); }
			catch { return reject('PROCEDURE_NOT_VERIFIED', 'Procedure catalog metadata is malformed or claims unsupported verification state.'); }
			if (procedure.metadata.id !== request.procedure.id || procedure.metadata.version !== request.procedure.version || procedure.metadata.packageDigest !== request.procedure.artifactDigest || procedure.artifactDigest !== request.procedure.artifactDigest || procedure.verified !== true || procedure.metadata.signature.state !== 'unverified' || procedure.metadata.retirement !== 'active') {
				return reject('PROCEDURE_IDENTITY_MISMATCH', 'Approved procedure no longer matches its verified catalog entry.');
			}
			if (procedure.inputSchemaDigest !== current.record.inputSchemaDigest || procedure.policyDigest !== current.record.policyDigest) { return reject('PROCEDURE_IDENTITY_MISMATCH', 'Approved procedure schema or policy binding changed.'); }
			if (!procedure.validateArguments(request.arguments)) { return reject('ARGUMENT_SCHEMA_INVALID', 'Arguments no longer match the procedure input schema.'); }
			const evidence = await this.dependencies.resolveCurrentEvidence(request.evidence.snapshotId);
			if (!evidence) { return reject('EVIDENCE_UNAVAILABLE', 'Core cannot resolve the approved evidence snapshot.'); }
			if (!evidence.current || evidence.digest !== request.evidence.digest) { return reject('EVIDENCE_STALE', 'Approved evidence snapshot is stale or its digest changed.'); }
			if (!this.withinProcedureCeilings(request.resourceLimits, procedure.metadata) || !this.dependencies.validatePolicy({ capabilities: request.capabilities, resourceLimits: request.resourceLimits, procedure: procedure.metadata })) {
				return reject('CAPABILITY_UNSUPPORTED', 'Approved capability or resource policy is no longer valid.');
			}
		} catch { return reject('DEPENDENCY_UNAVAILABLE', 'Core could not revalidate current project, procedure, evidence, or policy state.'); }
		return { ok: true, approval: clone(current.record) };
	}

	async revoke(approvalId: string): Promise<ControlledValidationAuthorizationResult> {
		return await this.withApprovalLock(approvalId, () => this.revokeUnlocked(approvalId));
	}

	private async revokeUnlocked(approvalId: string): Promise<ControlledValidationAuthorizationResult> {
		const current = this.approvals.get(approvalId);
		if (!current) { return reject('APPROVAL_NOT_FOUND', 'Approval is unavailable in this Core process.'); }
		if (current.record.status === 'expired') { return reject('APPROVAL_EXPIRED', 'Approval has expired.'); }
		if (this.clock.monotonicNow() >= current.monotonicDeadline) {
			this.replaceStatus(approvalId, 'expired');
			try { await this.history.recordStatus(approvalId, 'expired', new Date(this.clock.wallNow()).toISOString()); }
			catch { return reject('HISTORY_STORAGE_UNAVAILABLE', 'Approval expired and was invalidated, but its expiry event could not be durably recorded.'); }
			return reject('APPROVAL_EXPIRED', 'Approval has expired.');
		}
		if (current.record.status === 'revoked') { return { ok: true, approval: clone(current.record) }; }
		if (current.record.status !== 'approved') { return reject('APPROVAL_EXPIRED', 'Approval is no longer active.'); }
		this.replaceStatus(approvalId, 'revoked');
		try { await this.history.recordStatus(approvalId, 'revoked', new Date(this.clock.wallNow()).toISOString()); }
		catch { return reject('HISTORY_STORAGE_UNAVAILABLE', 'Approval was invalidated in memory, but its revocation event could not be durably recorded.'); }
		return { ok: true, approval: clone(this.approvals.get(approvalId)!.record) };
	}

	/** Durably consumes an authorization into a non-executable start commitment. This does not launch work. */
	async commitStart(approvalId: string, expectedAuthorizationBindingDigest: string, candidate: unknown): Promise<ControlledValidationStartCommitResultV1> {
		try { return await this.withApprovalLock(approvalId, async () => {
			const current = this.approvals.get(approvalId);
			if (!current) { return { ok: false, code: 'APPROVAL_NOT_FOUND', message: 'Approval is unavailable in this Core process.' }; }
			if (current.record.status === 'consumed') {
				const prior = await this.lifecycle?.queryStart(approvalId).catch(() => undefined);
				return { ok: false, code: 'APPROVAL_ALREADY_CONSUMED', message: 'Approval already has a durable start commitment.', ...(prior ? { historical: prior } : {}) };
			}
			if (current.record.status === 'revoked') { return { ok: false, code: 'APPROVAL_REVOKED', message: 'Approval was revoked before start commitment.' }; }
			if (current.record.status !== 'approved') { return { ok: false, code: 'APPROVAL_EXPIRED', message: 'Approval is not active.' }; }
			if (expectedAuthorizationBindingDigest !== authorizationBindingDigest(approvalId, current.record.requestDigest)) {
				return { ok: false, code: 'APPROVAL_BINDING_MISMATCH', message: 'Expected authorization binding does not match the active approval.' };
			}
			const checked = await this.validateUnlocked(approvalId, candidate);
			if (!checked.ok) {
				const code = checked.code === 'APPROVAL_REVOKED' ? 'APPROVAL_REVOKED' : checked.code === 'APPROVAL_EXPIRED' ? 'APPROVAL_EXPIRED' : checked.code === 'APPROVAL_NOT_FOUND' ? 'APPROVAL_NOT_FOUND' : 'APPROVAL_BINDING_MISMATCH';
				return { ok: false, code, message: checked.message };
			}
			if (!this.lifecycle) { return { ok: false, code: 'START_COMMIT_UNAVAILABLE', message: 'Core lifecycle persistence is unavailable.' }; }
			const approval = checked.approval;
			let committed;
			try {
				committed = await this.lifecycle.commitStart({
					approvalId, timestamp: new Date(this.clock.wallNow()).toISOString(), approvalHistory: current.approvalHistory,
					authorizationBindingDigest: expectedAuthorizationBindingDigest, projectRoot: approval.project.root, projectIdentity: approval.project.identity,
					permittedTargets: approval.project.permittedTargets, procedureId: approval.procedure.id, procedureVersion: approval.procedure.version,
					artifactDigest: approval.procedure.artifactDigest, argumentDigest: approval.argumentDigest,
					evidenceSnapshotId: approval.evidence.snapshotId, evidenceDigest: approval.evidence.digest,
					capabilities: approval.capabilities, resourceLimits: approval.resourceLimits,
				});
			} catch (error) { return { ok: false, code: 'START_COMMIT_UNAVAILABLE', message: error instanceof Error ? error.message.slice(0, 256) : 'Durable start commitment failed.' }; }
			this.replaceStatus(approvalId, 'consumed');
			const event = committed.event;
			return { ok: true, duplicate: committed.duplicate, receipt: {
				schemaVersion: 1, approvalId, executionId: event.executionId, commitmentEventId: event.eventId,
				authorizationBindingDigest: event.authorizationBindingDigest, consumedAt: event.timestamp, status: 'consumed', nonExecutable: true,
			} };
		}); } catch (error) {
			if (error instanceof AuthorizationLockTimeoutError) { return { ok: false, code: 'START_COMMIT_UNAVAILABLE', message: error.message }; }
			throw error;
		}
	}

	inspectHistory(): Promise<HistoricalApprovalRecordV1[]> { return this.history.query(); }

	async invalidateAllForShutdown(): Promise<{ ok: true; invalidatedCount: number } | { ok: false; code: 'HISTORY_STORAGE_UNAVAILABLE'; message: string }> {
		const active = [...this.approvals.values()].filter(item => item.record.status === 'approved');
		for (const item of active) { this.replaceStatus(item.record.approvalId, 'invalidated-by-restart'); }
		for (const item of active) {
			try { await this.history.recordStatus(item.record.approvalId, 'shutdown', new Date(this.clock.wallNow()).toISOString()); }
			catch { return { ok: false, code: 'HISTORY_STORAGE_UNAVAILABLE', message: 'Active approvals were invalidated in memory during shutdown, but one or more history events could not be recorded.' }; }
		}
		return { ok: true, invalidatedCount: active.length };
	}

	/** Explicit hard boundary: a committed start receipt does not provide a procedure launch path. */
	assertExecutable(_approvalId: string): never {
		throw Object.assign(new Error('Controlled Validation start commitments are non-executable; no reviewed execution supervisor is available.'), { code: 'APPROVAL_NON_EXECUTABLE' as const });
	}

	private replaceStatus(approvalId: string, status: ControlledValidationAuthorizationStatusV1): void {
		const entry = this.approvals.get(approvalId)!;
		this.approvals.set(approvalId, { ...entry, record: deepFreeze({ ...entry.record, status }) });
	}

	private async withApprovalLock<T>(approvalId: string, task: () => Promise<T>): Promise<T> {
		if (!isUuid(approvalId)) { return await task(); }
		const prior = this.approvalLocks.get(approvalId) ?? Promise.resolve();
		let release!: () => void;
		const current = new Promise<void>(resolve => { release = resolve; });
		const queued = prior.then(() => current);
		this.approvalLocks.set(approvalId, queued);
		let timer: unknown;
		const acquired = await Promise.race([prior.then(() => true), new Promise<boolean>(resolve => { timer = this.lockTimer.setTimeout(() => resolve(false), 15_000); })]);
		if (timer !== undefined) { this.lockTimer.clearTimeout(timer); }
		if (!acquired) {
			release();
			if (this.approvalLocks.get(approvalId) === queued) { this.approvalLocks.delete(approvalId); }
			throw new AuthorizationLockTimeoutError();
		}
		try { return await task(); }
		finally { release(); if (this.approvalLocks.get(approvalId) === queued) { this.approvalLocks.delete(approvalId); } }
	}

	private withinProcedureCeilings(limits: ControlledValidationResourceLimitsV1, metadata: ProcedureMetadataV1): boolean {
		return limits.timeoutMs <= metadata.resourceCeilings.timeoutMs
			&& limits.memoryBytes <= metadata.resourceCeilings.memoryBytes
			&& limits.outputBytes <= metadata.resourceCeilings.outputBytes
			&& limits.processCount <= metadata.resourceCeilings.processCount;
	}
}

export function authorizationBindingDigest(approvalId: string, requestDigest: string): string {
	if (!isUuid(approvalId) || !/^[a-f0-9]{64}$/.test(requestDigest)) { throw new TypeError('Invalid authorization binding values.'); }
	return digestCanonical({ schemaVersion: 1, approvalId, requestDigest });
}

export function validateControlledValidationAuthorizationRequest(value: unknown): ControlledValidationAuthorizationRequestV1 {
	canonicalize(value);
	const root = exactRecord(value, ['schemaVersion','requestId','consent','project','procedure','arguments','argumentDigest','evidence','capabilities','resourceLimits']);
	if (root.schemaVersion !== 1 || !isRequestId(root.requestId)) { throw new TypeError('Invalid authorization request envelope.'); }
	const consent = exactRecord(root.consent, ['disclosureVersion','confirmed']);
	if (consent.disclosureVersion !== CONTROLLED_VALIDATION_CONSENT_DISCLOSURE_VERSION || consent.confirmed !== true) { throw new TypeError('Explicit current consent confirmation is required.'); }
	const project = exactRecord(root.project, ['root','identity','permittedTargets']);
	if (typeof project.root !== 'string' || project.root.length < 1 || project.root.length > 4096 || !isCanonicalAbsoluteRoot(project.root) || !isDigest(project.identity) || !Array.isArray(project.permittedTargets) || project.permittedTargets.length < 1 || project.permittedTargets.length > 128) { throw new TypeError('Invalid project scope.'); }
	const targets = project.permittedTargets as unknown[];
	if (!targets.every(isCanonicalRelativeTarget) || new Set(targets).size !== targets.length || targets.some((target, index) => index > 0 && String(targets[index - 1]) >= String(target))) { throw new TypeError('Targets must be unique, sorted canonical project-relative paths.'); }
	const procedure = exactRecord(root.procedure, ['id','version','artifactDigest']);
	if (typeof procedure.id !== 'string' || !/^[a-z][a-z0-9.-]*:[A-Za-z0-9][A-Za-z0-9._:/-]{0,159}$/.test(procedure.id) || typeof procedure.version !== 'string' || !isSemVer(procedure.version) || !isDigest(procedure.artifactDigest)) { throw new TypeError('Invalid procedure identity.'); }
	if (!isDigest(root.argumentDigest)) { throw new TypeError('Invalid argument digest.'); }
	const evidence = exactRecord(root.evidence, ['snapshotId','digest']);
	if (!isSafeId(evidence.snapshotId) || !isDigest(evidence.digest)) { throw new TypeError('Invalid evidence snapshot identity.'); }
	const capabilities = exactRecord(root.capabilities, ['filesystem','network','projectWrites','inheritedCredentials']);
		if (!['none','read-only','read-write'].includes(String(capabilities.filesystem)) || !['none','restricted','unrestricted'].includes(String(capabilities.network)) || typeof capabilities.projectWrites !== 'boolean' || typeof capabilities.inheritedCredentials !== 'boolean') { throw new TypeError('Invalid capability declaration.'); }
	const resourceLimits = exactRecord(root.resourceLimits, ['timeoutMs','memoryBytes','outputBytes','processCount']);
	for (const field of ['timeoutMs','memoryBytes','outputBytes','processCount']) { if (!Number.isSafeInteger(resourceLimits[field]) || Number(resourceLimits[field]) < 1) { throw new TypeError('Invalid resource limits.'); } }
	return deepFreeze(clone({
		schemaVersion: 1 as const, requestId: root.requestId, consent: { disclosureVersion: consent.disclosureVersion, confirmed: true as const },
		project: { root: project.root, identity: project.identity, permittedTargets: [...targets] as string[] },
		procedure: { id: procedure.id, version: procedure.version, artifactDigest: procedure.artifactDigest },
		arguments: root.arguments as JsonValue, argumentDigest: root.argumentDigest,
		evidence: { snapshotId: evidence.snapshotId, digest: evidence.digest },
		capabilities: { filesystem: capabilities.filesystem as 'none' | 'read-only' | 'read-write', network: capabilities.network as 'none' | 'restricted' | 'unrestricted', projectWrites: capabilities.projectWrites as boolean, inheritedCredentials: capabilities.inheritedCredentials as boolean },
		resourceLimits: { timeoutMs: resourceLimits.timeoutMs as number, memoryBytes: resourceLimits.memoryBytes as number, outputBytes: resourceLimits.outputBytes as number, processCount: resourceLimits.processCount as number },
	}));
}

function exactRecord(value: unknown, keys: string[]): Record<string, any> {
	if (!value || typeof value !== 'object' || Array.isArray(value) || (Object.getPrototypeOf(value) !== Object.prototype && Object.getPrototypeOf(value) !== null)) { throw new TypeError('Expected a plain object.'); }
	const record = value as Record<string, unknown>;
	if (Object.keys(record).some(key => !keys.includes(key)) || keys.some(key => !Object.prototype.hasOwnProperty.call(record, key))) { throw new TypeError('Unknown or missing authorization field.'); }
	return record;
}
function isRequestId(value: unknown): value is string { return typeof value === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9._:-]{0,127}$/.test(value); }
function isSafeId(value: unknown): value is string { return typeof value === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9._:-]{0,127}$/.test(value); }
function isDigest(value: unknown): value is string { return typeof value === 'string' && /^sha256:[a-f0-9]{64}$/.test(value); }
function canonicalDigest(value: unknown): string { return `sha256:${digestCanonical(value)}`; }
function isUuid(value: unknown): value is string { return typeof value === 'string' && /^[a-f0-9]{8}-[a-f0-9]{4}-[1-8][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/i.test(value); }
function isSemVer(value: unknown): value is string { return typeof value === 'string' && /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(value); }
function isCanonicalRelativeTarget(value: unknown): value is string {
	if (typeof value !== 'string' || value.length < 1 || value.length > 1024 || value.includes('\\') || value.startsWith('/') || /^[a-zA-Z]:/.test(value)) { return false; }
	const parts = value.split('/');
	return parts.every(part => part.length > 0 && part !== '.' && part !== '..') && !value.includes('\0');
}
function isCanonicalAbsoluteRoot(value: string): boolean {
	if (value.includes('\\') || value.includes('\0')) { return false; }
	if (/^[a-zA-Z]:\//.test(value)) { return path.win32.normalize(value).replace(/\\/g, '/') === value && value[0] === value[0]!.toUpperCase(); }
	return value.startsWith('/') && path.posix.normalize(value) === value;
}
function sameCanonicalRoot(requested: string, canonical: string): boolean { return requested === canonical; }
function reject(code: ControlledValidationAuthorizationRejectionCode, message: string): ControlledValidationAuthorizationResult { return { ok: false, code, message }; }
function errorMessage(error: unknown): string { return error instanceof Error ? error.message.slice(0, 256) : 'Invalid authorization request.'; }
function clone<T>(value: T): T { return JSON.parse(JSON.stringify(value)) as T; }
function deepFreeze<T>(value: T): T { if (value && typeof value === 'object' && !Object.isFrozen(value)) { Object.freeze(value); for (const child of Object.values(value as object)) { deepFreeze(child); } } return value; }
